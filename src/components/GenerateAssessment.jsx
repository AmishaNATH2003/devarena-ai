
import { useState } from "react";
import { Sparkles, Loader2, AlertCircle } from "lucide-react";

export default function GenerateAssessment({ onGenerated }) {
  const [technology, setTechnology] = useState("java");
  const [difficulty, setDifficulty] = useState("beginner");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const generateAssessment = async () => {
    if (loading) return;

    setLoading(true);
    setError("");

    try {
      const response = await fetch("/api/generate-assessment", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          technology,
          difficulty,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          data.error || "Unable to generate assessment."
        );
      }

      if (!data.assessment) {
        throw new Error("No assessment was returned.");
      }

      // Parent component will open the generated project.
      onGenerated?.(data.assessment);
    } catch (err) {
      setError(err.message || "Something went wrong.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <section className="rounded-2xl border border-indigo-100 bg-white p-6 shadow-sm">
      <div className="flex items-center gap-3">
        <div className="rounded-xl bg-indigo-600 p-3 text-white">
          <Sparkles size={22} />
        </div>

        <div>
          <h2 className="text-xl font-bold">
            Generate an AI Assessment
          </h2>

          <p className="mt-1 text-sm text-slate-500">
            Practice a new engineering task generated by Gemini.
          </p>
        </div>
      </div>

      <div className="mt-6 grid gap-4 sm:grid-cols-2">
        <div>
          <label
            htmlFor="assessment-technology"
            className="mb-2 block text-sm font-medium"
          >
            Technology
          </label>

          <select
            id="assessment-technology"
            value={technology}
            onChange={(event) =>
              setTechnology(event.target.value)
            }
            className="w-full rounded-xl border border-slate-200 bg-white p-3"
          >
            <option value="java">Java</option>
            <option value="sql">SQL</option>
            <option value="react">React</option>
          </select>
        </div>

        <div>
          <label
            htmlFor="assessment-difficulty"
            className="mb-2 block text-sm font-medium"
          >
            Difficulty
          </label>

          <select
            id="assessment-difficulty"
            value={difficulty}
            onChange={(event) =>
              setDifficulty(event.target.value)
            }
            className="w-full rounded-xl border border-slate-200 bg-white p-3"
          >
            <option value="beginner">Beginner</option>
            <option value="intermediate">Intermediate</option>
            <option value="advanced">Advanced</option>
          </select>
        </div>
      </div>

      <button
        type="button"
        onClick={generateAssessment}
        disabled={loading}
        className="mt-6 flex w-full items-center justify-center gap-2 rounded-xl bg-indigo-600 px-5 py-3 font-semibold text-white hover:bg-indigo-700 disabled:opacity-60"
      >
        {loading ? (
          <>
            <Loader2 size={18} className="animate-spin" />
            Generating your project...
          </>
        ) : (
          <>
            <Sparkles size={18} />
            Generate Assessment
          </>
        )}
      </button>

      {error && (
        <p
          role="alert"
          className="mt-4 flex items-center gap-2 text-sm text-red-600"
        >
          <AlertCircle size={17} />
          {error}
        </p>
      )}

      <p className="mt-4 text-xs text-slate-500">
        Generated assessments are AI-created practice projects.
        Their code and expected behavior must be validated before
        being used as reliable assessments.
      </p>
    </section>
  );
}
