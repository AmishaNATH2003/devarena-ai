
import { supabase } from "./supabase";

// Require a verified signed-in user.
async function getCurrentUserId() {
  const { data, error } = await supabase.auth.getUser();

  if (error) throw error;

  if (!data.user) {
    throw new Error("Please sign in to save your progress.");
  }

  return data.user.id;
}

// Keep numeric scores within the database's 0-100 range.
function validScore(value) {
  if (value === null || value === undefined || value === "") {
    return null;
  }

  const score = Number(value);

  if (!Number.isFinite(score) || score < 0 || score > 100) {
    throw new Error("Score must be between 0 and 100.");
  }

  return score;
}

// Save or update the latest result for one assessment.
export async function saveCloudAssessment(result) {
  const userId = await getCurrentUserId();

  if (!result?.assessmentId) {
    throw new Error("Assessment ID is required.");
  }

  const payload = {
    user_id: userId,
    assessment_id: String(result.assessmentId),
    title: result.title || "Coding Assessment",
    language: result.language || null,
    status: result.completed ? "completed" : "attempted",
    score: validScore(result.score),
    result,
    completed_at: result.completedAt || new Date().toISOString(),
    updated_at: new Date().toISOString(),
  };

  const { data, error } = await supabase
    .from("assessment_progress")
    .upsert(payload, {
      onConflict: "user_id,assessment_id",
    })
    .select()
    .single();

  if (error) throw error;

  return data;
}

// Fetch the signed-in user's assessment results.
export async function getCloudAssessments() {
  const userId = await getCurrentUserId();

  const { data, error } = await supabase
    .from("assessment_progress")
    .select("*")
    .eq("user_id", userId)
    .order("completed_at", { ascending: false });

  if (error) throw error;

  return data || [];
}

// Save a separate interview attempt.
// Uses the UUID generated by interviewStorage when available.
export async function saveCloudInterview(result) {
  const userId = await getCurrentUserId();

  if (!result || !Array.isArray(result.answers)) {
    throw new Error("Valid interview results are required.");
  }

  const payload = {
    user_id: userId,
    title: result.assessmentTitle || "AI Interview",
    interview_type: result.interviewType || "technical",
    interview_mode: result.mode || "assignment",
    target_role: result.targetRole || null,
    score: validScore(result.averageScore),
    questions_count: result.questionsAnswered ?? result.answers.length,
    result,
    completed_at: result.completedAt || new Date().toISOString(),
  };

  // Preserve the existing UUID if supplied, to avoid duplicates
  // when the same attempt is retried.
  if (
    typeof result.id === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(result.id)
  ) {
    payload.id = result.id;
  }

  const { data, error } = await supabase
    .from("interview_attempts")
    .upsert(payload, { onConflict: "id" })
    .select()
    .single();

  if (error) throw error;

  return data;
}

// Fetch the signed-in user's interview history.
export async function getCloudInterviews() {
  const userId = await getCurrentUserId();

  const { data, error } = await supabase
    .from("interview_attempts")
    .select("*")
    .eq("user_id", userId)
    .order("completed_at", { ascending: false });

  if (error) throw error;

  return data || [];
}
